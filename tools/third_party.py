#!/usr/bin/env python3
"""Write THIRD-PARTY.md: every crate built into DSlot, for nibOS and for the stock OS, with its
licence, and the licence and copyright texts each crate ships, which go with every copy.

    python3 tools/third_party.py > THIRD-PARTY.md

Reads `cargo metadata` for the handheld's target with each feature; the crates' own texts come
from cargo's registry (`cargo fetch` first if a crate's source is missing).
"""

import json
import subprocess
import sys
from pathlib import Path

TARGET = "aarch64-unknown-linux-gnu"
FEATURES = ["nibos", "stock"]
TEXTS = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE")


def graph(feature):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--features", feature,
         "--filter-platform", TARGET],
        check=True, capture_output=True, text=True).stdout
    meta = json.loads(out)
    ids = {n["id"] for n in meta["resolve"]["nodes"]}
    return meta["resolve"]["root"], [p for p in meta["packages"] if p["id"] in ids]


def texts(package):
    """The licence and notice files beside a crate's Cargo.toml, by name."""
    here = Path(package["manifest_path"]).parent
    found = []
    for f in sorted(here.iterdir()):
        if f.is_file() and f.name.upper().startswith(TEXTS):
            found.append((f.name, f.read_text(errors="replace").strip()))
    if package.get("license_file"):
        f = here / package["license_file"]
        if f.is_file() and f.name not in {n for n, _ in found}:
            found.append((f.name, f.read_text(errors="replace").strip()))
    return found


def main():
    crates, used = {}, {}
    for feature in FEATURES:
        root, packages = graph(feature)
        for p in packages:
            if p["id"] == root:
                continue
            crates[p["id"]] = p
            used.setdefault(p["id"], []).append(feature)

    rows = sorted(crates.values(), key=lambda p: (p["name"], p["version"]))
    w = sys.stdout.write
    w("# Third-party notices\n\n")
    w("DSlot is GPL-3.0-or-later (LICENSE). Built into it are the crates below, each under its\n"
      "own licence, all of them compatible with GPL-3.0 (docs/licences.md). Their licence and\n"
      "copyright texts follow the list. Generated by `tools/third_party.py`; do not edit.\n\n")
    w("Also in the program: Roboto Condensed, under the SIL Open Font License 1.1 (OFL.txt); and,\n"
      "for RetroAchievements, rcheevos 12.4.0 (MIT, vendored in nibkit's nib-cheevos/rcheevos\n"
      "with its LICENSE, installed as LICENSE.rcheevos), which is C, not a crate, so it is not\n"
      "in the list below. SDL2 is not built in: DSlot links to the system's libSDL2 (zlib\n"
      "licence).\n\n")
    w("| Crate | Version | Licence | Built for |\n|---|---|---|---|\n")
    for p in rows:
        lic = p["license"] or f"see {p.get('license_file')}"
        w(f"| {p['name']} | {p['version']} | {lic} | {', '.join(used[p['id']])} |\n")

    # Identical texts (the many copies of the MIT and Apache licences) are printed once, under
    # every crate that ships them.
    by_text = {}
    for p in rows:
        for name, body in texts(p):
            by_text.setdefault(body, []).append(f"{p['name']} {p['version']} ({name})")
    w("\n## Licence and copyright texts\n")
    for body, owners in by_text.items():
        w("\n### " + "; ".join(owners) + "\n\n```\n" + body + "\n```\n")
    missing = [p for p in rows if not texts(p)]
    if missing:
        w("\n## Crates that ship no licence file\n\n")
        for p in missing:
            w(f"- {p['name']} {p['version']}: {p['license']}"
              f"{', ' + p['repository'] if p.get('repository') else ''}\n")


if __name__ == "__main__":
    main()
